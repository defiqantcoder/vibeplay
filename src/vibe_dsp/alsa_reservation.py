"""Direct ALSA hardware device reservation and MPD transport configuration.

Builds direct bit-perfect hardware output mapping (hw:), transparent fallback
driver chains (plughw:), and PipeWire bit-perfect fallback sinks.
"""

from __future__ import annotations

import logging
from pathlib import Path

from vibe_dsp.models import AudioEndpoint

logger = logging.getLogger(__name__)

DEFAULT_MPD_CONF_DIR = Path("~/.config/mpd/conf.d").expanduser()


def check_alsa_device_status(card_index: int, device_index: int = 0) -> str:
    """Query ALSA procfs to determine if hardware PCM subdevice is available.

    Args:
        card_index: ALSA card index.
        device_index: ALSA device index.

    Returns:
        str: 'closed' (available), 'RUNNING' (in-use), or 'unknown'.
    """
    status_file = Path(f"/proc/asound/card{card_index}/pcm{device_index}p/sub0/status")
    if status_file.exists():
        try:
            return status_file.read_text(encoding="utf-8", errors="replace").strip()
        except Exception:
            return "unknown"
    return "unknown"


def generate_mpd_audio_outputs(
    primary_endpoint: AudioEndpoint,
    fallback_endpoint: AudioEndpoint | None = None,
) -> str:
    """Generate MPD audio output configuration block with transparent fallback chain.

    Generates:
    1. Direct hardware output ('hw:<card>,<dev>') with auto_resample disabled.
    2. Transparent format fallback ('plughw:<card>,<dev>') if hardware rejects rate.
    3. Bit-perfect PipeWire output as final fallback.

    Args:
        primary_endpoint: Prioritized hardware endpoint (usually connected USB DAC).
        fallback_endpoint: Optional secondary endpoint (e.g. onboard speakers).

    Returns:
        str: MPD configuration text block.
    """
    card_name = primary_endpoint.card_name
    hw_dev = primary_endpoint.hw_device
    plug_dev = primary_endpoint.plughw_device

    # Check for DSD capability
    has_dsd = any("DSD" in fmt.upper() for fmt in primary_endpoint.formats)
    dop_setting = '    dop             "yes"\n' if has_dsd else ""

    outputs = [
        f"""# ==============================================================================
# Bit-Perfect Audio Outputs - Generated by vibe-dsp (Phase 5.1)
# Primary: {card_name} ({hw_dev})
# ==============================================================================

# 1. Primary Direct Hardware Output (Strict Bit-Perfect Bypassing OS Mixers)
audio_output {{
    type            "alsa"
    name            "Bit-Perfect ALSA [Direct] ({card_name})"
    device          "{hw_dev}"
    auto_resample   "no"
    auto_channels   "no"
    auto_format     "no"
{dop_setting}    mixer_type      "none"
}}

# 2. Transparent Fallback Driver (ALSA Plug layer if hardware rejects sample format)
audio_output {{
    type            "alsa"
    name            "Bit-Perfect ALSA [Plug Fallback] ({card_name})"
    device          "{plug_dev}"
    auto_resample   "no"
    mixer_type      "none"
}}
"""
    ]

    # If an onboard speaker fallback endpoint was provided, add it as secondary output
    if fallback_endpoint and fallback_endpoint.hw_device != hw_dev:
        fb_name = fallback_endpoint.card_name
        fb_hw = fallback_endpoint.hw_device
        fb_plug = fallback_endpoint.plughw_device
        outputs.append(
            f"""# 3. Secondary Hardware Output (Fallback Speakers: {fb_name})
audio_output {{
    type            "alsa"
    name            "Speakers ALSA ({fb_name})"
    device          "{fb_hw}"
    auto_resample   "no"
    mixer_type      "none"
}}

audio_output {{
    type            "alsa"
    name            "Speakers Plug ({fb_name})"
    device          "{fb_plug}"
    auto_resample   "no"
    mixer_type      "none"
}}
"""
        )

    # 4. PipeWire Universal Sink Fallback
    outputs.append(
        """# 4. PipeWire Transport Fallback (Shared Sound Server Mode)
audio_output {
    type            "pipewire"
    name            "PipeWire Sound Server"
}
"""
    )

    return "\n".join(outputs)


def write_mpd_audio_outputs_config(
    content: str,
    output_path: Path | None = None,
) -> Path:
    """Save the MPD audio output configuration snippet to disk.

    Args:
        content: MPD configuration text block.
        output_path: Target destination path (defaults to ~/.config/mpd/conf.d/bitperfect.conf).

    Returns:
        Path: Resolved configuration file path.
    """
    target = output_path or (DEFAULT_MPD_CONF_DIR / "bitperfect.conf")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    logger.info("Wrote MPD bit-perfect audio outputs config to %s", target)
    return target
