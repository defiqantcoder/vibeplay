"""System configuration backup and automatic rollback script generation."""

from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
from datetime import datetime
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

DEFAULT_BACKUP_ROOT = Path("~/.config/vibe-dsp/backups").expanduser()


def create_backup(
    targets: list[Path],
    backup_root: Path | None = None,
) -> tuple[Path, Path]:
    """Create timestamped backup directory and executable rollback script.

    Guarantees compliance with safety rules: no persistent system configuration
    is applied without an automated, atomic rollback mechanism.

    Args:
        targets: List of target configuration files that will be created or modified.
        backup_root: Directory to store backups (defaults to ~/.config/vibe-dsp/backups).

    Returns:
        tuple[Path, Path]: (backup_dir_path, rollback_script_path).
    """
    root = backup_root or DEFAULT_BACKUP_ROOT
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_dir = root / timestamp
    backup_dir.mkdir(parents=True, exist_ok=True)

    manifest_items: list[dict[str, Any]] = []
    rollback_commands: list[str] = [
        "#!/usr/bin/env bash",
        "# Automatic rollback script generated by vibe-dsp",
        f"# Created at: {datetime.now().isoformat()}",
        "set -euo pipefail",
        'echo "[vibe-dsp] Initiating configuration rollback..."',
        "",
    ]

    for target in targets:
        target_path = target.expanduser().resolve()
        target_name = target_path.name
        existed = target_path.exists()

        if existed:
            backup_file = backup_dir / target_name
            shutil.copy2(target_path, backup_file)
            manifest_items.append(
                {
                    "target": str(target_path),
                    "action": "restore",
                    "backup_file": str(backup_file),
                }
            )
            rollback_commands.append(f'echo "Restoring {target_path}..."')
            rollback_commands.append(f'cp -f "{backup_file}" "{target_path}"')
        else:
            manifest_items.append(
                {
                    "target": str(target_path),
                    "action": "delete",
                }
            )
            rollback_commands.append(f'echo "Removing newly created {target_path}..."')
            rollback_commands.append(f'rm -f "{target_path}"')

    # Add service restart commands to rollback
    rollback_commands.extend(
        [
            "",
            'echo "Restarting PipeWire user services..."',
            "if command -v systemctl >/dev/null 2>&1; then",
            "    systemctl --user restart pipewire pipewire-pulse 2>/dev/null || true",
            "fi",
            "",
            'echo "[vibe-dsp] Rollback successfully completed."',
        ]
    )

    # Write manifest.json
    manifest_file = backup_dir / "manifest.json"
    manifest_data = {
        "timestamp": timestamp,
        "created_at": datetime.now().isoformat(),
        "items": manifest_items,
    }
    manifest_file.write_text(json.dumps(manifest_data, indent=2), encoding="utf-8")

    # Write rollback.sh and make executable
    rollback_script = backup_dir / "rollback.sh"
    rollback_script.write_text("\n".join(rollback_commands) + "\n", encoding="utf-8")
    os.chmod(rollback_script, 0o755)

    logger.info("Created configuration backup and rollback script at %s", backup_dir)
    return backup_dir, rollback_script


def find_latest_backup(backup_root: Path | None = None) -> Path | None:
    """Locate the most recent backup directory containing a rollback.sh script.

    Args:
        backup_root: Directory to search (defaults to ~/.config/vibe-dsp/backups).

    Returns:
        Path | None: Path to latest rollback.sh script, or None if none found.
    """
    root = backup_root or DEFAULT_BACKUP_ROOT
    if not root.exists():
        return None

    subdirs = sorted(
        [d for d in root.iterdir() if d.is_dir() and (d / "rollback.sh").exists()],
        key=lambda d: d.name,
        reverse=True,
    )
    if subdirs:
        return subdirs[0] / "rollback.sh"
    return None


def execute_rollback(rollback_path: Path) -> tuple[bool, str]:
    """Execute a rollback script.

    Args:
        rollback_path: Path to rollback.sh.

    Returns:
        tuple[bool, str]: Success status and execution logs.
    """
    if not rollback_path.exists():
        return False, f"Rollback script not found: {rollback_path}"

    try:
        res = subprocess.run(
            ["bash", str(rollback_path)],
            capture_output=True,
            text=True,
            timeout=15.0,
            check=False,
        )
        output = (res.stdout + "\n" + res.stderr).strip()
        return res.returncode == 0, output
    except Exception as err:
        return False, f"Rollback execution error: {err}"
