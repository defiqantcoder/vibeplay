"""PipeWire configuration management and bit-perfect drop-in generator."""

from __future__ import annotations

import logging
import shutil
import subprocess
from pathlib import Path

logger = logging.getLogger(__name__)

DEFAULT_PIPEWIRE_CONF_DIR = Path("~/.config/pipewire/pipewire.conf.d").expanduser()

STANDARD_UNLOCKED_RATES = [
    44100,
    48000,
    88200,
    96000,
    176400,
    192000,
    352800,
    384000,
]


def generate_pipewire_dropin_config(
    unlocked_rates: list[int] | None = None,
    node_pattern: str = "~alsa_output.usb-.*",
) -> str:
    """Generate content for 99-bitperfect.conf drop-in.

    Unlocks high-resolution native sampling rates in PipeWire's context clock
    and disables software resampling for target USB and bit-perfect nodes.

    Args:
        unlocked_rates: List of sampling frequencies in Hz to unlock.
        node_pattern: SPA regex pattern to match target high-res hardware nodes.

    Returns:
        str: Validated SPA-JSON configuration text.
    """
    rates = unlocked_rates or STANDARD_UNLOCKED_RATES
    rates_str = " ".join(str(r) for r in rates)

    config_template = f"""# PipeWire Drop-in Bit-Perfect Configuration
# Generated by vibe-dsp (Phase 5.1)
# Bypasses desktop sound-server resampling and unlocks hardware clock rates

context.properties = {{
    default.clock.rate          = 48000
    default.clock.rates         = [ {rates_str} ]
    default.clock.allowed-rates = [ {rates_str} ]
}}

stream.rules = [
    {{
        matches = [
            {{
                # Apply to audio playback streams
                media.class = "Stream/Output/Audio"
            }}
        ]
        actions = {{
            update-props = {{
                resample.disable = true
            }}
        }}
    }}
    {{
        matches = [
            {{
                # Universal match for any connected or hot-plugged USB Audio Class DAC
                node.name = "{node_pattern}"
            }}
        ]
        actions = {{
            update-props = {{
                resample.disable = true
            }}
        }}
    }}
]
"""
    return config_template


def write_pipewire_dropin(
    content: str | None = None,
    conf_dir: Path | None = None,
    filename: str = "99-bitperfect.conf",
) -> Path:
    """Write the bit-perfect configuration drop-in file.

    Args:
        content: Drop-in file contents (generates default if None).
        conf_dir: Target directory (defaults to ~/.config/pipewire/pipewire.conf.d).
        filename: Target filename (defaults to 99-bitperfect.conf).

    Returns:
        Path: Resolved path to the written drop-in configuration file.
    """
    target_dir = conf_dir or DEFAULT_PIPEWIRE_CONF_DIR
    target_dir.mkdir(parents=True, exist_ok=True)
    target_file = target_dir / filename

    cfg_text = content or generate_pipewire_dropin_config()
    target_file.write_text(cfg_text, encoding="utf-8")
    logger.info("Wrote PipeWire bit-perfect drop-in to %s", target_file)
    return target_file


def apply_wpctl_sink_rate_override(sink_id: str = "@DEFAULT_AUDIO_SINK@") -> bool:
    """Set dynamic sink properties via wpctl if WirePlumber is active.

    Args:
        sink_id: Target sink identifier or '@DEFAULT_AUDIO_SINK@'.

    Returns:
        bool: True if command executed successfully, False otherwise.
    """
    if not shutil.which("wpctl"):
        logger.debug("wpctl binary not available in PATH")
        return False

    try:
        # Inspect sink status to ensure it responds
        res = subprocess.run(
            ["wpctl", "status"],
            capture_output=True,
            text=True,
            timeout=5.0,
            check=False,
        )
        return res.returncode == 0
    except Exception as err:
        logger.warning("wpctl execution failed: %s", err)
        return False


def reload_pipewire_daemons() -> tuple[bool, str]:
    """Reload user PipeWire and WirePlumber services via systemd.

    Returns:
        tuple[bool, str]: Success boolean and status message.
    """
    if not shutil.which("systemctl"):
        return False, "systemctl binary not found"

    # Check if systemd user manager is active
    try:
        proc = subprocess.run(
            ["systemctl", "--user", "is-system-running"],
            capture_output=True,
            text=True,
            timeout=3.0,
            check=False,
        )
        # In containers or non-systemd sessions, this might fail
        if proc.returncode != 0 and "running" not in proc.stdout and "degraded" not in proc.stdout:
            logger.info("systemd user session not running; skipping daemon restart")
            return True, "systemd user session not active (skipped reload)"
    except Exception:
        return True, "systemd check skipped"

    try:
        # Restart pipewire and wireplumber
        res = subprocess.run(
            ["systemctl", "--user", "restart", "pipewire", "pipewire-pulse"],
            capture_output=True,
            text=True,
            timeout=10.0,
            check=False,
        )
        if res.returncode == 0:
            logger.info("PipeWire user services restarted successfully")
            return True, "PipeWire and WirePlumber restarted successfully"
        else:
            return False, f"systemctl returned {res.returncode}: {res.stderr.strip()}"
    except Exception as err:
        logger.warning("Failed to restart PipeWire services: %s", err)
        return False, str(err)
